function seed(kind) {
  if (!R.isOwner()) return R.toast("دسترسی نداری", "err");
  if (R._seeding) return R.toast("همین الان در حال انجامه ⏳", "err");
  R._seeding = true;
  var list = kind === "anime" ? AN : NW;
  R.toast("شروع شد — " + R.fa(list.length) + " مورد ⏳", "ok");
  var jobs = list.map(function (r) {
    var o = kind === "anime"
      ? { title: r[0], jp: r[1], icon: r[2], gen: r[3], st: r[4], rate: r[5],
          desc: r[6], by: R.ME, seed: true }
      : { title: r[0], cat: r[1], icon: r[2], body: r[3], by: R.ME, views: 0, seed: true };
    return R.add(kind, o).catch(function () {});
  });
  Promise.all(jobs).then(function () {
    R._seeding = false;
    R.toast("تمام شد ✅ " + R.fa(list.length) + " مورد اضافه شد", "ok");
  });
}

function wipe(kind) {
  if (!R.isOwner()) return R.toast("دسترسی نداری", "err");
  var src = kind === "anime" ? R.ANIME : R.NEWS;
  var ks = Object.keys(src || {}).filter(function (k) { return src[k] && src[k].seed; });
  if (!ks.length) return R.toast("نمونه‌ای برای پاک کردن نیست", "err");
  ks.forEach(function (k) { R.set(kind + "/" + k, null).catch(function () {}); });
  R.toast("نمونه‌ها پاک شد 🧹 (" + R.fa(ks.length) + ")", "ok");
}

function head(secId, kind, label) {
  if (!R.isOwner()) return;
  var s = R.$(secId); if (!s) return;
  var h = s.querySelector(".head"); if (!h) return;
  if (R.$("sd-" + kind)) return;
  var b1 = R.el("button", "btn p mini sbtn", "🌱 " + label);
  b1.id = "sd-" + kind;
  b1.addEventListener("click", function () { seed(kind); });
  var b2 = R.el("button", "btn mini sbtn", "🧹 پاک کردن نمونه‌ها");
  b2.addEventListener("click", function () { wipe(kind); });
  h.appendChild(b1); h.appendChild(b2);
}

