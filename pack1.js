  if (rail && !R.$("dmItem")) {
    var it = document.createElement("div");
    it.className = "ditem";
    it.id = "dmItem";
    it.setAttribute("data-go", "inbox");
    it.innerHTML = "<i>💌</i>پیام‌ها";
    var chat = rail.querySelector('.ditem[data-go="chat"]');
    if (chat && chat.parentNode) chat.parentNode.insertBefore(it, chat.nextSibling);
    else rail.appendChild(it);
  }
  head("sec-anime", "anime", "افزودن ۳۰ انیمه نمونه");
  head("sec-news", "news", "افزودن ۱۲ خبر نمونه");
