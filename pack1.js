function nameOf(uid) {
  if (!uid) return;
  if (R.USERS && R.USERS[uid]) return set(uid, R.USERS[uid].name || "کاربر");
  R.PNMC = R.PNMC || {};
  if (R.PNMC[uid]) return set(uid, R.PNMC[uid]);
  R.get("users/" + uid).then(function (u) {
    R.PNMC[uid] = (u && u.name) || "کاربر";
    set(uid, R.PNMC[uid]);
  }).catch(function () {});
  function set(id, n) {
    R.qa('[data-uname="' + id + '"]').forEach(function (e) { e.textContent = n; });
  }
}

R.inbox = function () {
  var box = R.$("inboxBox"); if (!box) return;
  if (!R.ME) {
    box.innerHTML = '<div class="empty">برای دیدن پیام‌ها وارد حساب شو 💌</div>';
    return;
  }
  var all = R.PDM || {}, mine = [];
  Object.keys(all).forEach(function (k) { if (k.indexOf(R.ME) > -1) mine.push(k); });
  if (!mine.length) {
    box.innerHTML = '<div class="empty">هنوز پیامی نداری 💌<br>' +
      'روی پروفایل یک کاربر بزن و «پیام» بده</div>';
    return;
  }
  var rows = mine.map(function (k) {
    var o = all[k] || {}, arr = [];
    Object.keys(o).forEach(function (x) { if (o[x] && o[x].t) arr.push(o[x]); });
    arr.sort(function (a, b) { return (a.t || 0) - (b.t || 0); });
    var last = arr[arr.length - 1] || {};
    return {
      uid: k.replace(R.ME, "").replace(/[^A-Za-z0-9]/g, ""),
      text: last.text || "—", t: last.t || 0, n: arr.length
    };
  }).filter(function (r) { return r.uid; })
    .sort(function (a, b) { return (b.t || 0) - (a.t || 0); });

  box.innerHTML = rows.map(function (r) {
    return '<div class="ibx" data-dmgo="' + R.esc(r.uid) + '">' +
      '<div class="ib">💌</div>' +
      '<div class="grow" style="min-width:0">' +
      '<div class="it" data-uname="' + R.esc(r.uid) + '">کاربر</div>' +
      '<div class="is">' + R.esc(r.text) + '</div></div>' +
      '<div class="ic2">' + R.time(r.t) + '</div></div>';
  }).join("");
  rows.forEach(function (r) { nameOf(r.uid); });
};

